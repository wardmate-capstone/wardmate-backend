DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname = 'iam') THEN
        CREATE SCHEMA iam;
    END IF;
END $EF$;


CREATE TABLE permissions (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    permission_code character varying(100) NOT NULL,
    permission_name character varying(255) NOT NULL,
    module character varying(50) NOT NULL,
    CONSTRAINT pk_permissions PRIMARY KEY (id)
);


CREATE TABLE rbac_audit_logs (
    id uuid NOT NULL,
    actor_user_id uuid NOT NULL,
    action character varying(100) NOT NULL,
    target_user_id uuid,
    role_id integer,
    permission_id integer,
    details jsonb NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_rbac_audit_logs PRIMARY KEY (id)
);


CREATE TABLE roles (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    role_name character varying(50) NOT NULL,
    description text,
    CONSTRAINT pk_roles PRIMARY KEY (id)
);


CREATE TABLE wards (
    id uuid NOT NULL,
    code character varying(50) NOT NULL,
    name character varying(255) NOT NULL,
    CONSTRAINT pk_wards PRIMARY KEY (id)
);


CREATE TABLE role_permissions (
    role_id integer NOT NULL,
    permission_id integer NOT NULL,
    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_permissions_permission_id FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_roles_role_id FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE
);


CREATE TABLE users (
    id uuid NOT NULL,
    security_stamp uuid NOT NULL,
    verified_phone_number text,
    username character varying(100) NOT NULL,
    email character varying(255) NOT NULL,
    password_hash character varying(255) NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    assigned_categories integer[] NOT NULL DEFAULT (ARRAY[]::integer[]),
    ward_id uuid,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT fk_users_wards_ward_id FOREIGN KEY (ward_id) REFERENCES wards (id) ON DELETE RESTRICT
);


CREATE TABLE refresh_tokens (
    id uuid NOT NULL,
    user_id uuid NOT NULL,
    token character varying(500) NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    is_revoked boolean NOT NULL DEFAULT FALSE,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT fk_refresh_tokens_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);


CREATE TABLE iam.user_otps (
    id uuid NOT NULL,
    user_id uuid NOT NULL,
    target_phone_number character varying(20),
    otp_hash character varying(64) NOT NULL,
    channel character varying(10) NOT NULL,
    purpose character varying(30) NOT NULL,
    expires_at_utc timestamp with time zone NOT NULL,
    attempts integer NOT NULL,
    is_used boolean NOT NULL,
    created_at_utc timestamp with time zone NOT NULL,
    CONSTRAINT pk_user_otps PRIMARY KEY (id),
    CONSTRAINT ck_user_otps_attempts CHECK (attempts BETWEEN 0 AND 5),
    CONSTRAINT ck_user_otps_channel CHECK (channel IN ('EMAIL','SMS')),
    CONSTRAINT ck_user_otps_purpose CHECK (purpose IN ('CHANGE_PASSWORD','FORGOT_PASSWORD','VERIFY_PHONE')),
    CONSTRAINT fk_user_otps_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);


CREATE TABLE user_profiles (
    user_id uuid NOT NULL,
    full_name character varying(255) NOT NULL,
    identity_number character varying(20),
    phone_number character varying(20),
    date_of_birth date,
    gender character varying(10),
    permanent_address text,
    temporary_address text,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_user_profiles PRIMARY KEY (user_id),
    CONSTRAINT fk_user_profiles_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);


CREATE TABLE user_roles (
    user_id uuid NOT NULL,
    role_id integer NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_roles_role_id FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);


CREATE TABLE iam.welcome_emails (
    id uuid NOT NULL,
    user_id uuid NOT NULL,
    attempts integer NOT NULL,
    next_attempt_at_utc timestamp with time zone NOT NULL,
    sent_at_utc timestamp with time zone,
    CONSTRAINT pk_welcome_emails PRIMARY KEY (id),
    CONSTRAINT fk_welcome_emails_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);


