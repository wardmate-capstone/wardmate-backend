CREATE EXTENSION IF NOT EXISTS unaccent;


CREATE TABLE procedure_categories (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    category_name character varying(255) NOT NULL,
    description text,
    CONSTRAINT pk_procedure_categories PRIMARY KEY (id)
);


CREATE TABLE procedure_drafts (
    id uuid NOT NULL,
    status character varying(30) NOT NULL,
    blob_name character varying(255) NOT NULL,
    pdf_file_name character varying(255) NOT NULL,
    original_pdf_url character varying(500) NOT NULL,
    payload_json jsonb NOT NULL,
    warnings_json jsonb NOT NULL,
    extracted_text text NOT NULL,
    failure_code character varying(100),
    created_by character varying(255) NOT NULL,
    reviewed_by character varying(255),
    published_procedure_id uuid,
    revision uuid NOT NULL,
    lease_id uuid,
    lease_until timestamp with time zone,
    attempts integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_procedure_drafts PRIMARY KEY (id)
);


CREATE TABLE procedures (
    id uuid NOT NULL DEFAULT (gen_random_uuid()),
    category_id integer NOT NULL,
    procedure_code character varying(50) NOT NULL,
    title character varying(500) NOT NULL,
    original_pdf_url character varying(500),
    pdf_file_name character varying(255),
    issuing_authority character varying(255),
    executing_agency text,
    level_of_implementation character varying(50) NOT NULL DEFAULT 'Cấp Xã',
    target_audience character varying(255) NOT NULL DEFAULT 'Công dân Việt Nam',
    fee_summary character varying(255) NOT NULL DEFAULT 'Miễn phí',
    processing_time_summary character varying(255) NOT NULL DEFAULT '1 ngày',
    is_active boolean NOT NULL DEFAULT TRUE,
    status_change_reason text,
    content_payload jsonb NOT NULL,
    checklist_schema jsonb,
    form_definitions jsonb,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    updated_at timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_procedures PRIMARY KEY (id),
    CONSTRAINT fk_procedures_procedure_categories_category_id FOREIGN KEY (category_id) REFERENCES procedure_categories (id) ON DELETE RESTRICT
);


CREATE TABLE procedure_versions (
    id uuid NOT NULL DEFAULT (gen_random_uuid()),
    procedure_id uuid NOT NULL,
    version_number integer NOT NULL,
    decision_number character varying(100),
    original_pdf_url character varying(500),
    pdf_file_name character varying(255),
    effective_date date NOT NULL,
    snapshot_data jsonb NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_procedure_versions PRIMARY KEY (id),
    CONSTRAINT fk_procedure_versions_procedures_procedure_id FOREIGN KEY (procedure_id) REFERENCES procedures (id) ON DELETE RESTRICT
);


